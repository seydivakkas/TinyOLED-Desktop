class Font:
    """Bitmap font + icon repository."""

    CHAR_W       = CHAR_W
    CHAR_H       = CHAR_H
    CHAR_SPACING = CHAR_SPACING
    CHAR_STRIDE  = CHAR_W + CHAR_SPACING   # total advance per character

    @classmethod
    def glyph(cls, char: str) -> List[int]:
        """Return 5-column byte list for a single ASCII character."""
        return list(_FONT_5X7.get(char, _FONT_5X7.get('?', [0x22, 0x14, 0x08, 0x14, 0x22])))

    @classmethod
    def text_width(cls, text: str) -> int:
        """Calculate pixel width of a text string."""
        return len(text) * cls.CHAR_STRIDE - cls.CHAR_SPACING

    @classmethod
    def icon(cls, name: str) -> List[int]:
        """Return 8-row × 8-bit list for a named icon. Returns empty box if not found."""
        return list(_ICONS_8X8.get(name, [0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF]))

    @classmethod
    def icon_names(cls) -> List[str]:
        return list(_ICONS_8X8.keys())
